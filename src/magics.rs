pub const fn gen_rook_attacks(sq: usize, blockers: u128) -> u128 {
    let mut bb: u128 = 0;
    let mut tgt = sq;

    // Vertical: Downwards
    while tgt / 9 < 8 {
        tgt += 9;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    // Horizontal: Right
    let mut tgt = sq;
    while tgt % 9 < 8 {
        tgt += 1;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    // Vertical: Upwards
    let mut tgt = sq;
    while tgt / 9 > 0 {
        tgt -= 9;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    // Horizontal: Left
    let mut tgt = sq;
    while tgt % 9 > 0 {
        tgt -= 1;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    bb
}

pub const fn gen_bishop_attacks(sq: usize, blockers: u128) -> u128 {
    let mut bb: u128 = 0;
    let mut tgt = sq;

    // Diagonal: Bottom-left direction
    while tgt % 9 > 0 && tgt / 9 < 8 {
        tgt += 8;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    // Diagonal: Bottom-right direction
    let mut tgt = sq;
    while tgt % 9 < 8 && tgt / 9 < 8 {
        tgt += 10;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    // Diagonal: Top-left direction
    let mut tgt = sq;
    while tgt % 9 > 0 && tgt / 9 > 0 {
        tgt -= 10;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    // Diagonal: Top-right direction
    let mut tgt = sq;
    while tgt % 9 < 8 && tgt / 9 > 0 {
        tgt -= 8;
        bb |= 1 << tgt;
        if blockers & (1 << tgt) > 0 { break; }
    }

    bb
}

pub const fn gen_lance_attacks(sq: usize, side: usize, blockers: u128) -> u128 {
    let mut bb: u128 = 0;
    let mut tgt = sq;

    if side == 0 {
        // Vertical: Upwards
        let mut tgt = sq;
        while tgt / 9 < 8 {
            tgt += 9;
            bb |= 1 << tgt;
            if blockers & (1 << tgt) > 0 { break; }
        }
    }
    else {
        // Vertical: Downwards
        while tgt / 9 > 0 {
            tgt -= 9;
            bb |= 1 << tgt;
            if blockers & (1 << tgt) > 0 { break; }
        }
    }

    bb
}