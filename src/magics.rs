fn create_table(table_size: usize, deltas: &[i8], magics: &[MagicEntry; Square::COUNT]) -> Vec<u128> {
    let mut table = vec![bits::NONE; table_size];
    for sq in 0..Square::COUNT as u8 {
        let magic = &magics[sq as usize];
        let mask = magic.mask;

        let mut blockers = bits::NONE;
        loop {
            let moves = sliding_attacks(deltas, sq, blockers);
            let index = magic.index(blockers);
            table[index] = moves;

            // Carry-Rippler trick
            blockers = blockers.wrapping_sub(mask) & mask;
            if blockers == bits::NONE {
                break;
            }
        }
    }
    table
}

// Mask off the attacks on the edges of the board,
// since they are redundant for creating the index
pub fn attack_mask(deltas: &[i8], sq: u8) -> u128 {
    let occ = bits::NONE;
    let mut bb = sliding_attacks(deltas, sq, occ);
    let file = Square::file(sq);
    let rank = Square::rank(sq);
    if file != 8 {
        bb &= !bits::FILE_1;
    }
    if file != 0 {
        bb &= !bits::FILE_9;
    }
    if rank != 8 {
        bb &= !bits::RANK_A;
    }
    if rank != 0 {
        bb &= !bits::RANK_I;
    }
    bb
}

pub fn sliding_attacks(deltas: &[i8], sq: u8, occ: u128) -> u128 {
    let mut bb: u128 = 0;

    for &delta in deltas {
        let mut sq_prev = sq;
        let mut sq_opt = try_delta(sq, delta);

        while let Some(sq_tmp) = sq_opt {
            let valid_file = (Square::file(sq_prev) as i8 - Square::file(sq_tmp) as i8).abs() <= 1;
            let valid_rank = (Square::rank(sq_prev) as i8 - Square::rank(sq_tmp) as i8).abs() <= 1;
            if valid_file && valid_rank {
                bb |= bits::bb(sq_tmp);

                if bits::contains(occ, sq_tmp) {
                    break;
                }

                sq_prev = sq_tmp;
                sq_opt = try_delta(sq_tmp, delta);
            } else {
                break;
            }
        }
    }

    bb
}

#[inline]
pub fn try_delta(sq: u8, delta: i8) -> Option<u8> {
    let res = sq as i16 + delta as i16;
    if Square::is_valid(res as u8) {
        Some(res as u8)
    } else {
        None
    }
}

const fn gen_bishop_attacks_table() -> [u128; BISHOP_TABLE_SIZE]  {
    let mut table = [0; BISHOP_TABLE_SIZE];
    let mut sq: u8 = 0;

    while sq < 81 {
        let entry = &BISHOP_MAGICS[sq as usize];
        let mut subset: u128 = 0;

        let attacks = gen_bishop_attacks(sq as usize, subset);
        let blockers = subset;
        let idx = entry.index(blockers);
        table[idx] = attacks;
        subset = subset.wrapping_sub(entry.mask) & entry.mask;

        while subset != 0 {
            let attacks = gen_bishop_attacks(sq as usize, subset);
            let blockers = subset;
            let idx = entry.index(blockers);
            table[idx] = attacks;

            subset = subset.wrapping_sub(entry.mask) & entry.mask;
        }

        sq += 1;
    }

    table
}


